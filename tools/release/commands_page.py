def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def render() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from cm1core.gui.commands import API

    rows = []
    for endpoint in API:
        where = WHERE.get(endpoint.action)
        if where is None:
            raise SystemExit(f"commands_page.py: no screen name for the API action {endpoint.action!r}; add it to WHERE")
        rows.append(f"| {_cell(where)} | `{_cell(endpoint.command)}` | {_cell(endpoint.note or '')} |")
    return HEADER + "\n".join(rows) + "\n" + FOOTER


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/COMMANDS.md differs; write nothing")
    arguments = parser.parse_args(argv)
    page = render()
    if arguments.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else ""
        if current != page:
            print("docs/COMMANDS.md is behind the GUI's API table: run tools/release/commands_page.py")
            return 1
        return 0
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
